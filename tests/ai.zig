const std = @import("std");
const ai = @import("ai");

const Random = struct {
    seed: u32,
    calls: u32 = 0,

    fn integer(self: *Random) u32 {
        self.seed = self.seed *% 1664525 +% 1013904223;
        return self.seed;
    }

    pub fn next(self: *Random) f64 {
        self.calls += 1;
        return @as(f64, @floatFromInt(self.integer())) / 4294967296.0;
    }

    fn pick(self: *Random, values: []const f64) f64 {
        return values[@as(usize, self.integer()) % values.len];
    }
};

const Commands = struct {
    actions: [4]ai.Action = undefined,
    count: u32 = 0,

    pub fn move(self: *Commands, action: ai.Action) void {
        self.actions[self.count] = action;
        self.count += 1;
    }

    fn code(self: *const Commands, serve_type: c_int, random_calls: u32) u32 {
        var value = @as(u32, @intCast(serve_type + 1)) | self.count << 3 | random_calls << 16;
        for (self.actions[0..self.count], 0..) |action, i| value |= @as(u32, @backingInt(action)) << @intCast(6 + i * 2);
        return value;
    }
};

// Identical input generation in ai_reference.mjs; controller code is independent.
fn snapshot(random: *Random, frame: usize) ai.Snapshot {
    var values: [12]f64 = .{
        random.pick(&.{ 200, 499, 500, 539, 540, 579, 580, 600, 619, 620, 699, 700, 729, 730, 770, 800, 840, 860, 900, 990 }),
        random.pick(&.{ 35, 50, 51, 100, 124, 125, 129, 130, 131, 200, 249, 250, 299, 300, 400 }),
        random.pick(&.{ -15, -8, -1, 0, 1, 8, 15 }),
        random.pick(&.{ -22, -13, -12, -3, -2, -1, 0, 12, 13, 22 }),
        random.pick(&.{ 150, 199, 200, 249, 250, 251, 299, 300, 301, 400 }),
        random.pick(&.{ 0, 29, 100 }),
        0,
        0,
        random.pick(&.{ 555, 574, 575, 580, 585, 666, 700, 770, 799, 800, 801, 840, 845, 860, 900, 901, 950 }),
        random.pick(&.{ 0, 29, 100 }),
        random.pick(&.{ -8, 0, 8 }),
        random.pick(&.{ -9, 0, 9 }),
    };
    if (frame % 3 == 0) {
        values[0] += 0.25;
        values[1] += 0.5;
        values[3] += 0.5;
    }
    return ai.Snapshot.fromArray(values);
}

test "stage 1-3 action sequences match the pinned OneSlime controllers" {
    // Generated by node tests/ai_reference.mjs ../oneslime-vball/OneSlime.min.js.
    // Each fingerprint includes every command in order, serve state and RNG count.
    const expected = [3][2]u32{
        .{ 1130116207, 3371291303 },
        .{ 1415510735, 2506721923 },
        .{ 516515579, 1818070614 },
    };
    for (expected, 0..) |row, stage| {
        for (row, 0..) |fingerprint, persistent| {
            var inputs: Random = .{ .seed = 0x51a1beef };
            var controller: ai.Controller = .{};
            var hash: u32 = 2166136261;
            for (0..4096) |frame| {
                const values = snapshot(&inputs, frame);
                var random: Random = .{ .seed = inputs.integer() };
                if (persistent == 0) controller.serve_type = @as(c_int, @intCast(inputs.integer() % 6)) - 1;
                var commands: Commands = .{};
                controller.step(@intCast(stage), values, &random, &commands);
                hash = (hash ^ commands.code(controller.serve_type, random.calls)) *% 16777619;
            }
            try std.testing.expectEqual(fingerprint, hash);
        }
    }
}
